// Generates src/agents/templates.generated.ts from 00-System/Output-Templates.md in the vault:
// the prep brief (template 5), the script block (6) and the Critic's checklist (13).
// Usage: node scripts/build-templates.mjs "<vault folder>"
import fs from "node:fs";
import path from "node:path";
const vault = process.argv[2]; if (!vault) { console.error("Give the vault folder"); process.exit(1); }
const md = fs.readFileSync(path.join(vault, "00-System/Output-Templates.md"), "utf8").replace(/^﻿/, "");
const section = (n) => { const m = md.match(new RegExp(`\\n---\\n+## ${n}\\. [^\\n]*\\n([\\s\\S]*?)(?=\\n---\\n+## \\d+\\. |$)`)); if (!m) throw new Error("template section " + n + " not found"); return m[1]; };
const code = (n) => { const m = section(n).match(/```markdown\n([\s\S]*?)\n```/); if (!m) throw new Error("no code block in template " + n); return m[1].trim(); };
const brief = code(5), script = code(6);
const additions = section(5).split("```").pop().trim();
const checklist = [...section(13).matchAll(/^\d+\. (.*)$/gm)].map((m) => m[1]);
if (!/## 1\. Your numbers/.test(brief) || !/## 9\. Assumptions/.test(brief)) throw new Error("prep brief template looks wrong");
if (checklist.length < 10) throw new Error("brief checklist too short: " + checklist.length);
const out = `// GENERATED by scripts/build-templates.mjs from the vault. Do not edit by hand.
export const PREP_BRIEF_TEMPLATE = ${JSON.stringify(brief)};
export const PREP_BRIEF_ADDITIONS = ${JSON.stringify(additions)};
export const SCRIPT_BLOCK_TEMPLATE = ${JSON.stringify(script)};
export const BRIEF_CHECKLIST: readonly string[] = ${JSON.stringify(checklist)};
`;
fs.writeFileSync(new URL("../src/agents/templates.generated.ts", import.meta.url), out);
console.log("templates:", brief.length, "chars brief,", checklist.length, "checklist items");
