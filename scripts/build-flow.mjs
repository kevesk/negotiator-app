// Generates src/orchestrator/flow.generated.ts from the vault:
//  - the machine-readable flow (YAML block in 00-System/Flow-Overview.md)
//  - slot tiers and ask text (tables in 00-System/Slot-Definitions.md)
// Usage: node scripts/build-flow.mjs "<vault folder>"
import fs from "node:fs";
import path from "node:path";
import { parse } from "yaml";
const vault = process.argv[2]; if (!vault) { console.error("Give the vault folder"); process.exit(1); }
const read = (rel) => fs.readFileSync(path.join(vault, rel), "utf8").replace(/^﻿/, "");

const flowMd = read("00-System/Flow-Overview.md");
const y = flowMd.match(/## Machine-readable flow \(YAML\)[\s\S]*?```yaml\n([\s\S]*?)\n```/);
if (!y) throw new Error("flow YAML not found");
const flow = parse(y[1]);
for (const k of ["stages", "modifiers", "limits", "ui"]) if (!flow[k]) throw new Error("flow YAML lacks " + k);

const slotsMd = read("00-System/Slot-Definitions.md");
const derived = [...slotsMd.matchAll(/^\| `([a-z_0-9]+)` \| (researcher|numbers engine|offer analyzer|evidence builder|coach) \|/gm)].map((m) => m[1]);
const slots = {};
for (const line of slotsMd.split("\n")) {
  if (!line.startsWith("| `")) continue;
  const cells = line.split("|").slice(1, -1).map((c) => c.trim());
  const id = cells[0].match(/^`([a-z_0-9]+)`/)?.[1]; if (!id || slots[id] || derived.includes(id)) continue;
  const head = cells.slice(1, 4).join(" ");
  const byPath = [...head.matchAll(/([AB]) \(P([0-3])\)/g)];
  let tier;
  if (byPath.length) tier = Object.fromEntries(byPath.map((m) => [m[1], Number(m[2])]));
  else { const t = head.match(/P([0-3])/); if (!t) continue; tier = Number(t[1]); }
  const ask = cells.find((c, i) => i > 0 && /^["“]/.test(c))?.replace(/^["“]|["”]$/g, "") ?? null;
  slots[id] = { tier, ask };
}
if (Object.keys(slots).length < 40) throw new Error("too few slots parsed: " + Object.keys(slots).length);

const out = `// GENERATED by scripts/build-flow.mjs from the vault. Do not edit by hand.
export const FLOW = ${JSON.stringify(flow)} as const;
export const SLOT_DEFS: Record<string, { tier: number | Record<string, number>; ask: string | null }> = ${JSON.stringify(slots)};
export const DERIVED_SLOTS: readonly string[] = ${JSON.stringify(derived)};
`;
fs.mkdirSync(new URL("../src/orchestrator/", import.meta.url), { recursive: true });
fs.writeFileSync(new URL("../src/orchestrator/flow.generated.ts", import.meta.url), out);
console.log("flow:", flow.stages.length, "stages,", Object.keys(flow.modifiers).length, "modifiers;", Object.keys(slots).length, "slots,", derived.length, "derived");
